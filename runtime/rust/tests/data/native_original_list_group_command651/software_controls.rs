fn unhex(input: &str) -> Vec<u8> {
    input
        .as_bytes()
        .as_chunks::<2>()
        .0
        .iter()
        .map(|pair| u8::from_str_radix(core::str::from_utf8(pair).unwrap(), 16).unwrap())
        .collect()
}
fn category(name: &str) -> &str {
    match name {
        "int" | "wideInt" | "wide" => "integer",
        "double" | "coerced-double" => "double",
        "none" | "string" => "string",
        other => other,
    }
}
