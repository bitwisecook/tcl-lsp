fn unhex(text: &str) -> Vec<u8> {
    text.as_bytes()
        .chunks_exact(2)
        .map(|digits| u8::from_str_radix(core::str::from_utf8(digits).unwrap(), 16).unwrap())
        .collect()
}
fn category(kind: &str) -> &str {
    if matches!(kind, "int" | "wideInt") {
        "integer"
    } else {
        kind
    }
}
