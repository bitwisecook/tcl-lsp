"""Parser for Tcl ``tclIndex`` auto-loading index files.

A ``tclIndex`` file (generated by ``auto_mkindex``) maps proc names to
the source files that define them.  The format is version 2.0, unchanged
since Tcl 8.0::

    set auto_index(procName) [list source [file join $dir filename.tcl]]

Variants include ``::tcl::Pkg::source`` (Tcl 9.0) and an optional
``-encoding`` flag (Tcl 8.6+).
"""

from __future__ import annotations

import logging
import os
import re
from dataclasses import dataclass
from pathlib import Path

log = logging.getLogger(__name__)


@dataclass(frozen=True, slots=True)
class AutoIndexEntry:
    """A single proc -> file mapping from a tclIndex file."""

    proc_name: str  # e.g. "::http::geturl" or "myProc"
    source_file: str  # absolute path to the providing file


# Matches all common tclIndex line variants:
#   set auto_index(name) [list source [file join $dir file.tcl]]
#   set auto_index(::ns::name) [list ::tcl::Pkg::source [file join $dir file.tcl]]
#   set auto_index(name) [list source -encoding utf-8 [file join $dir file.tcl]]
_AUTO_INDEX_RE = re.compile(
    r"set\s+auto_index\(([^)]+)\)\s+"
    r"\[list\s+(?:::tcl::Pkg::)?source\s+"
    r"(?:-encoding\s+\S+\s+)?"
    r"\[file\s+join\s+\$dir\s+([^\]]+)\]\]"
)


def parse_tcl_index(tcl_index_path: str) -> list[AutoIndexEntry]:
    """Parse a tclIndex file and return proc->file mappings.

    Returns an empty list if the file cannot be read or contains no
    valid entries.  Referenced files that do not exist on disk are
    silently skipped.
    """
    try:
        content = Path(tcl_index_path).read_text(
            encoding="utf-8",
            errors="replace",
        )
    except Exception:
        log.debug("auto_index: failed to read %s", tcl_index_path, exc_info=True)
        return []

    index_dir = os.path.dirname(tcl_index_path)
    entries: list[AutoIndexEntry] = []

    for match in _AUTO_INDEX_RE.finditer(content):
        proc_name = match.group(1).strip()
        filename = match.group(2).strip().strip('"')
        full_path = os.path.join(index_dir, filename)
        if os.path.isfile(full_path):
            entries.append(AutoIndexEntry(proc_name=proc_name, source_file=full_path))

    if entries:
        log.debug(
            "auto_index: parsed %d entries from %s",
            len(entries),
            tcl_index_path,
        )
    return entries
