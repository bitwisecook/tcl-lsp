"""Data model for F5 BIG-IP configuration objects (package facade).

Re-exports the full public surface of the BIG-IP data model.  The
implementation is split per F5 module so each file stays a navigable
size:

- :mod:`._enums` — ``DataGroupType``, ``ProfileType``.
- :mod:`._minimal` — the shared minimal dataclass + per-F5-module
  aliases used by long-tail kinds, plus the generic-stanza
  fallback (:class:`BigipGenericObject`) for any unknown stanza.
- :mod:`._ltm` / :mod:`._net` / :mod:`._sys` / :mod:`._security` /
  :mod:`._apm` / :mod:`._cm` / :mod:`._gtm` / :mod:`._pem` /
  :mod:`._auth` — typed projections for each F5 module.
- :mod:`._config` — the top-level :class:`BigipConfig` container
  that knits every kind together.

This ``__init__`` is the stable import point: every existing call
site uses ``from dialects.f5.bigip.model import <name>`` and continues to
work after the split.
"""

