//! `cargo xtask gen-equivalence-packs` — the native Tcl 8.6 and iRules
//! command surfaces rendered as `SpecTcl` packs.
//!
//! Each pack holds, for every command name a dialect's assembled context
//! resolves, the spec it resolves to, rendered by the studio's own renderer
//! (the path `spectcl_roundtrip.rs` holds to field-for-field equality). The
//! packs are a measuring instrument, not a surface: nothing loads them in
//! production. They let a benchmark compare the same commands in the two
//! representations — native Rust and evaluated `SpecTcl` — so a cost that
//! differs between them is the representation's, not the command set's.

use std::fmt::Write as _;
use std::process::ExitCode;

use anyhow::Result;

use crate::util::{repo_root, write_if_changed};

const OUTPUT_DIR: &str = "rust/tcl-spectcl/equivalence";

/// `(dialect, pack name)`.
const SURFACES: &[(&str, &str)] = &[
    ("tcl8.6", "equivalent_tcl8_6"),
    ("f5-irules", "equivalent_f5_irules"),
];

fn render(dialect: &str, pack: &str) -> String {
    let environment = tcl_lsp_core::environment_for_dialect(dialect);
    let context = environment.default_context_registry();
    let drafts: Vec<tcl_spec_studio::draft::Draft> = context
        .visible_command_names()
        .into_iter()
        .filter_map(|name| context.resolve_command(name))
        .map(tcl_spec_studio::draft::from_command_spec)
        .collect();
    let (body, losses) = tcl_spec_studio::render_spectcl::render_pack_reporting(&drafts, pack);
    let mut out = String::new();
    let _ = writeln!(
        out,
        "# @generated by `cargo xtask gen-equivalence-packs` — do not edit by hand.\n\
         #\n\
         # The native `{dialect}` command surface ({} commands) as SpecTcl, for\n\
         # like-for-like comparison with the compiled-in specs. Not loaded by any\n\
         # product; see docs/design/registry/spectcl-compiled-surface-plan.md.\n\
         # Fields the renderer cannot carry: {}.\n",
        drafts.len(),
        losses.len(),
    );
    out.push_str(&body);
    out
}

pub fn run(check: bool) -> Result<ExitCode> {
    let mut stale = Vec::new();
    for &(dialect, pack) in SURFACES {
        let relative = format!("{OUTPUT_DIR}/{pack}.tclspec");
        let path = repo_root().join(&relative);
        let rendered = render(dialect, pack);
        if check {
            if std::fs::read_to_string(&path).unwrap_or_default() != rendered {
                stale.push(relative);
            }
            continue;
        }
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        if write_if_changed(&path, rendered)? {
            eprintln!("wrote {relative}");
        }
    }
    if stale.is_empty() {
        if check {
            eprintln!("OK: the equivalence packs match the native surfaces.");
        }
        return Ok(ExitCode::SUCCESS);
    }
    eprintln!(
        "stale against the native surfaces — run `cargo xtask gen-equivalence-packs`: {}",
        stale.join(", ")
    );
    Ok(ExitCode::from(1))
}
