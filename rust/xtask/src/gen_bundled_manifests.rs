//! `cargo xtask gen-bundled-manifests` — which bundled packs a process may
//! load manifest-only, precompiled into the binary every editor extension
//! ships (`rust/tcl-spectcl/src/bundled_manifest.rs`).
//!
//! A pack is deferrable when every command it declares requires a
//! closed-world vendor package; its row records the source hash it was
//! computed from and the packages that make it wanted
//! (`tcl_spectcl::demand`). `--check` holds the table to `specs/`.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::process::ExitCode;

use anyhow::{Context, Result};

use crate::util::{repo_root, write_if_changed};

const OUTPUT: &str = "rust/tcl-spectcl/src/bundled_manifest.rs";

const HEADER: &str = "//! The bundled packs a process may load manifest-only, and the packages
//! that make each one wanted.
//!
//! @generated by `cargo xtask gen-bundled-manifests` — do not edit by hand.
//! The packs under `specs/` are the source of truth; `--check` holds this
//! file to them.

use tcl_registry::arg_role::ArgRole;

/// One deferrable bundled pack.
pub struct BundledManifest {
    /// The pack's file name under `specs/`.
    pub file: &'static str,
    /// [`crate::demand::source_hash`] of the bytes this row describes.
    pub source_hash: u64,
    /// Every package one of its commands requires.
    pub packages: &'static [&'static str],
}

/// One bundled argument-role resolver whose answers depend on its word count
/// alone, run once at build time so no process starts a VM for it.
pub struct BundledRoleTable {
    /// The resolver body's hash (`hooks::service::body_hash`).
    pub body_hash: u64,
    /// Its answer at each word count from zero, `None` where it abstains.
    pub answers: &'static [Option<&'static [(u8, ArgRole)]>],
}

/// The deferrable bundled packs, by file name.
pub const BUNDLED_MANIFESTS: &[BundledManifest] = &[
";

/// A `u64` as a hex literal in groups of four, the spelling clippy reads.
fn hex(value: u64) -> String {
    let digits = format!("{value:016x}");
    let groups: Vec<&str> = (0..4).map(|i| &digits[i * 4..i * 4 + 4]).collect();
    format!("0x{}", groups.join("_"))
}

fn render() -> Result<String> {
    let dir = repo_root().join("specs");
    let mut files: Vec<_> = std::fs::read_dir(&dir)
        .with_context(|| format!("reading {}", dir.display()))?
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "tclspec"))
        .collect();
    files.sort();
    let mut out = crate::util::license_banner("//") + "\n" + HEADER;
    for path in files {
        let source = std::fs::read_to_string(&path)
            .with_context(|| format!("reading {}", path.display()))?;
        let pack = tcl_spectcl::evaluate_pack(&source);
        let mut packages = BTreeSet::new();
        let deferrable = !pack.commands.is_empty()
            && pack.commands.iter().all(|command| {
                command.spec.required_package.is_some_and(|package| {
                    packages.insert(package);
                    tcl_registry::model::surface::is_placement_gated_package(package)
                })
            });
        if !deferrable {
            continue;
        }
        let file = path
            .file_name()
            .and_then(|name| name.to_str())
            .context("pack file name")?;
        let packages: Vec<String> = packages.iter().map(|p| format!("{p:?}")).collect();
        let _ = write!(
            out,
            "    BundledManifest {{\n        file: {file:?},\n        source_hash: {},\n        \
             packages: &[{}],\n    }},\n",
            hex(tcl_spectcl::demand::source_hash(&source)),
            packages.join(", "),
        );
    }
    out.push_str("];\n\n/// The bundled packs' precompiled argument-role resolver tables.\npub const BUNDLED_ROLE_TABLES: &[BundledRoleTable] = &[\n");
    let set = tcl_spectcl::bundled::load_from(&dir);
    for (hash, answers) in tcl_spectcl::hooks::precompute_role_tables(&set) {
        let rows: Vec<String> = answers
            .iter()
            .map(|answer| match answer {
                None => "None".to_owned(),
                Some(roles) => format!(
                    "Some(&[{}])",
                    roles
                        .iter()
                        .map(|(index, role)| format!("({index}, ArgRole::{role:?})"))
                        .collect::<Vec<_>>()
                        .join(", ")
                ),
            })
            .collect();
        let _ = write!(
            out,
            "    BundledRoleTable {{\n        body_hash: {},\n        answers: &[\n            {},\n        ],\n    }},\n",
            hex(hash),
            rows.join(",\n            "),
        );
    }
    out.push_str("];\n");
    Ok(out)
}

pub fn run(check: bool) -> Result<ExitCode> {
    let path = repo_root().join(OUTPUT);
    let rendered = render()?;
    if std::fs::read_to_string(&path).unwrap_or_default() == rendered {
        if check {
            eprintln!("OK: {OUTPUT} matches specs/.");
        }
        return Ok(ExitCode::SUCCESS);
    }
    if check {
        eprintln!("{OUTPUT} is stale against specs/ — run `cargo xtask gen-bundled-manifests`");
        return Ok(ExitCode::from(1));
    }
    if write_if_changed(&path, rendered)? {
        eprintln!("wrote {OUTPUT}");
    }
    Ok(ExitCode::SUCCESS)
}
