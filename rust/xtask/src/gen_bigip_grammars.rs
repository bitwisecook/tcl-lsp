//! Generate the static editor grammars' BIG-IP configuration and iApp APL
//! vocabularies from their `tcl-bigip` owners — the same lexers the server's
//! semantic tokens come from — so the first-paint layers stop carrying their
//! own copies of those lists.
//!
//! ## What is projected
//!
//! | Owner (`tcl-bigip`) | Zed (`highlights.scm`) | VS Code (`*.tmLanguage.json`) |
//! |---|---|---|
//! | `apl::tokens::FIELD_TYPE_KEYWORDS` | `@type.builtin` field types | `field` |
//! | `apl::tokens::VALIDATOR_NAMES` | `@constant.builtin` validators | `validator` |
//! | `apl::tokens::ATTRIBUTE_KEYWORDS` | `@attribute` tokens | `attribute` |
//! | `apl::tokens::SECTION_KEYWORDS` | — (grammar node keywords) | `section` |
//! | `conf_tokens::MODULES` | — (a `tree-sitter-bigip` token) | `declaration` |
//! | `conf_tokens::KEYED_REFERENCES` | keyed bare value `@type` | `typed-object-reference`, `monitor-expression` |
//! | `value::monitor_expression::GRAMMAR_WORDS` | — | `monitor-expression` words |
//!
//! Each Zed query is also written to its grammar's own `queries/` copy, which
//! the grammar's tests read.
//!
//! ## What stays template
//!
//! Captures, scopes, rule shapes and their comments are presentation choices
//! and stay here. The Zed grammars' own node keywords (`section`, `table`,
//! `text`, and `tree-sitter-bigip`'s `module` token) are compiled into the
//! grammars' parsers, so a query cannot widen them; `zed-query-check` compiles
//! every generated query against those parsers, which rejects an attribute
//! token the APL grammar does not have.
//!
//! ## Limits
//!
//! Every projection is lexical display only: a word painted as a field type,
//! validator, module or object kind is not thereby a declared field, a
//! validator APL accepts at that point, an object that exists, or a path that
//! resolves — the server's analysis is what says so. A static grammar paints
//! a keyed value from its key alone; it neither reads the stanza it is in nor
//! knows the object graph.
//!
//! Run `cargo xtask gen-bigip-grammars` to (re)write the files; `--check`
//! verifies the committed files match, exiting non-zero on drift.

use std::fs;
use std::process::ExitCode;

use anyhow::{Context, Result, bail, ensure};
use serde_json::{Value, json};
use tcl_bigip::apl::tokens::{
    ATTRIBUTE_KEYWORDS, FIELD_TYPE_KEYWORDS, SECTION_KEYWORDS, VALIDATOR_NAMES,
};
use tcl_bigip::conf_tokens::{BigipTokenKind, KEYED_REFERENCES, MODULES};
use tcl_bigip::value::monitor_expression::GRAMMAR_WORDS;

use crate::util::{repo_root, write_if_changed};

const ZED_APL: &str = "editors/zed/languages/apl/highlights.scm";
const GRAMMAR_APL: &str = "grammars/tree-sitter-apl/queries/highlights.scm";
const ZED_BIGIP: &str = "editors/zed/languages/bigip/highlights.scm";
const GRAMMAR_BIGIP: &str = "grammars/tree-sitter-bigip/queries/highlights.scm";
const VSCODE_APL: &str = "editors/vscode/syntaxes/apl.tmLanguage.json";
const VSCODE_BIGIP: &str = "editors/vscode/syntaxes/bigip.tmLanguage.json";

/// The object kinds the `TextMate` grammar gives a typed-reference rule of
/// their own, with the server's semantic token type for that kind; the rule's
/// scope is the one `package.json` maps that token type to
/// ([`crate::editor_extensions::bigip_token_scope`]), so the static rule and
/// the semantic token land on the same theme colour. A monitor key is the
/// `monitor-expression` rule's opener instead; an untyped object key falls to
/// the generic path rules.
const TYPED_REFERENCE_KINDS: &[(BigipTokenKind, &str)] = &[
    (BigipTokenKind::Pool, "pool"),
    (BigipTokenKind::Profile, "profile"),
    (BigipTokenKind::Vlan, "vlan"),
];

/// The generated provenance note every projected `TextMate` rule carries.
const PROVENANCE: &str = "Generated by `cargo xtask gen-bigip-grammars`";

/// `word1|word2|…` — every word must be a plain identifier (letters, digits,
/// `_`, `-`), so it is literal in every regex dialect the targets use.
fn alternation(words: &[&str]) -> Result<String> {
    for word in words {
        ensure!(
            !word.is_empty()
                && word
                    .bytes()
                    .all(|b| b.is_ascii_alphanumeric() || b == b'_' || b == b'-'),
            "{word:?} is not a plain identifier"
        );
    }
    Ok(words.join("|"))
}

/// The keys whose bare value the owner types `kind`, in table order.
fn keys_of(kind: BigipTokenKind) -> Vec<&'static str> {
    KEYED_REFERENCES
        .iter()
        .filter(|(_, k)| *k == kind)
        .map(|(key, _)| *key)
        .collect()
}

/// Render a word list as `#any-of?` arguments, six to a line.
fn any_of(words: &[&str]) -> String {
    words
        .chunks(6)
        .map(|chunk| {
            let quoted: Vec<String> = chunk.iter().map(|w| format!("\"{w}\"")).collect();
            format!("    {}", quoted.join(" "))
        })
        .collect::<Vec<_>>()
        .join("\n")
}

fn render_zed_apl() -> Result<String> {
    let attributes = ATTRIBUTE_KEYWORDS
        .iter()
        .map(|w| format!("\"{w}\""))
        .collect::<Vec<_>>()
        .join(" ");
    Ok(format!(
        r#"; APL (F5 iApp presentation) highlights for Zed.
;
; DO NOT EDIT — the field-type, attribute and validator lists below are
; generated from the APL lexer's vocabulary (`tcl_bigip::apl::tokens`) by
; `cargo xtask gen-bigip-grammars`; the rest is a static template in that
; generator. A match is lexical display only: it names no declared field and
; proves no validator applies.
;
; Backed by `grammars/tree-sitter-apl`. Without it, Zed's APL language would
; point at the *Tcl* grammar and ship no query file at all, so an APL file
; would get no highlighting and — if queried — a garbage parse tree.
;
; The captures mirror the semantic-token types the server emits for APL, so the
; tree-sitter paint and the LSP paint agree rather than fighting.

(comment) @comment

; #include / #inline
(include (directive) @keyword)

(define "define" @keyword)
(define name: (identifier) @function.definition)
(define type: (identifier) @type)

(section "section" @keyword.control)
(section name: (identifier) @label)

(table "table" @keyword.control)
(table name: (identifier) @label)

(text_block "text" @keyword.control)
(text_entry target: (dotted_name) @property)

(optional_block "optional" @keyword.control)
(binary_expression operator: _ @operator)

; A field's type may be user-defined, so the grammar accepts any identifier and
; the built-in types are picked out here — the same split the Tcl queries use
; for built-in commands.
(field
  type: (identifier) @type.builtin
  (#any-of? @type.builtin
{field_types}))

(field type: (identifier) @type)
(field name: (identifier) @property)

(message_field "message" @type.builtin)

(attribute [{attributes}] @attribute)

; The validators APL ships with, named inside `validator "…"`. Only in that
; position — a bare `Number` in `display "Number"` is an ordinary string.
(attribute
  "validator"
  value: (string) @constant.builtin
  (#match? @constant.builtin "^\"({validators})\"$"))

(choice_mapping "=>" @operator)
(choice_mapping label: (string) @string.special)

(dotted_name) @property
(variable_substitution) @variable
(string) @string
(escape_sequence) @string.escape
(number) @number

["{{" "}}" "(" ")" "[" "]"] @punctuation.bracket
["," "."] @punctuation.delimiter
"#,
        field_types = any_of(FIELD_TYPE_KEYWORDS),
        validators = alternation(VALIDATOR_NAMES)?,
    ))
}

fn render_zed_bigip() -> String {
    let keys: Vec<&str> = KEYED_REFERENCES.iter().map(|(key, _)| *key).collect();
    format!(
        r#"; BIG-IP configuration highlights for Zed.
;
; DO NOT EDIT — the keyed-reference list below is generated from the BIG-IP
; configuration lexer's key table (`tcl_bigip::conf_tokens::KEYED_REFERENCES`)
; by `cargo xtask gen-bigip-grammars`; the rest is a static template in that
; generator. A match is lexical display only: it proves no object exists.
;
; Backed by `grammars/tree-sitter-bigip`. Without it, Zed's BIG-IP language
; would point at the *Tcl* grammar and ship no query file at all, so a
; `bigip.conf` would get no highlighting and a garbage parse tree.
;
; The captures mirror the BIG-IP semantic-token types the server emits. Where
; the grammar cannot be as specific as the server (a bare `/Common/x` does not
; say whether it names a pool or a monitor) it stays generic rather than guess:
; less specific, never contradictory.

(comment) @comment

(module) @keyword
(object_type) @keyword

; The partition of an object path is a namespace, as the server types it.
(object_path partition: (path_component) @namespace)
(object_path port: (port) @number)
(object_path route_domain: (number) @constant)

; A pool member's or virtual's final path component *is* an address. Without
; this it would fall through to the generic object-name capture and be painted
; a different colour than the server's `ipAddress` — the one place these two
; layers could contradict each other outright.
((object_path name: (path_component) @number)
 (#match? @number "^([0-9]{{1,3}}\\.){{3}}[0-9]{{1,3}}$"))

(object_path name: (path_component) @type)

; A key the server reads as naming its value's kind: the bare (unpathed) value
; is an object name, as the server types it. The key itself stays a property —
; the server types it as one.
(property
  name: (word) @_key
  value: (word) @type
  (#any-of? @_key
{keys}))

(property name: (word) @property)

(ip_address) @number
(ip_address port: (port) @number)
(encrypted) @string.special
(string) @string
(escape_sequence) @string.escape
(number) @number
(word) @variable

["{{" "}}"] @punctuation.bracket
"#,
        keys = any_of(&keys),
    )
}

/// Replace `repository.<rule>.<key>` in a parsed `TextMate` grammar.
fn set_rule(grammar: &mut Value, rule: &str, key: &str, value: Value) -> Result<()> {
    let slot = grammar
        .get_mut("repository")
        .and_then(|repository| repository.get_mut(rule))
        .and_then(Value::as_object_mut)
        .with_context(|| format!("repository.{rule} is not an object"))?;
    ensure!(
        slot.contains_key(key),
        "repository.{rule}.{key} is missing from the template"
    );
    slot.insert(key.to_owned(), value);
    Ok(())
}

/// The original comment of a rule, with the generated provenance appended
/// exactly once.
fn provenance_comment(grammar: &Value, rule: &str, owner: &str) -> Value {
    let original = grammar["repository"][rule]["comment"]
        .as_str()
        .unwrap_or_default();
    let base = original
        .split_once(&format!("\n\n{PROVENANCE}"))
        .map_or(original, |(head, _)| head);
    let note = format!("{PROVENANCE} from {owner}; lexical display only.");
    Value::from(if base.is_empty() {
        note
    } else {
        format!("{base}\n\n{note}")
    })
}

fn to_pretty(grammar: &Value) -> Result<String> {
    Ok(format!("{}\n", serde_json::to_string_pretty(grammar)?))
}

fn render_vscode_apl(original: &str) -> Result<String> {
    let mut grammar: Value = serde_json::from_str(original).context("parsing APL grammar")?;
    ensure!(
        ATTRIBUTE_KEYWORDS.contains(&"validator"),
        "the APL owner no longer has a `validator` attribute"
    );
    let ident = "[A-Za-z_][A-Za-z0-9_.]*";
    for (rule, owner, regex) in [
        (
            "section",
            "tcl_bigip::apl::tokens::SECTION_KEYWORDS",
            format!(
                r"(?<=^|\s)({})(?=\s|$|\{{)(?:\s+({ident}))?",
                alternation(SECTION_KEYWORDS)?
            ),
        ),
        (
            "validator",
            "tcl_bigip::apl::tokens::VALIDATOR_NAMES",
            format!(
                r#"(?<=^|\s)(validator)\s+(")({})(")"#,
                alternation(VALIDATOR_NAMES)?
            ),
        ),
        (
            "field",
            "tcl_bigip::apl::tokens::FIELD_TYPE_KEYWORDS",
            format!(
                r"(?<=^|\s)({})(?=\s)(?:\s+({ident}))?",
                alternation(FIELD_TYPE_KEYWORDS)?
            ),
        ),
        (
            "attribute",
            "tcl_bigip::apl::tokens::ATTRIBUTE_KEYWORDS",
            format!(r"(?<=^|\s)({})(?=\s|$)", alternation(ATTRIBUTE_KEYWORDS)?),
        ),
    ] {
        set_rule(&mut grammar, rule, "match", Value::from(regex))?;
        let comment = provenance_comment(&grammar, rule, owner);
        set_rule_comment(&mut grammar, rule, comment)?;
    }
    to_pretty(&grammar)
}

/// Set (or add) a rule's `comment`, keeping it the rule's first key.
fn set_rule_comment(grammar: &mut Value, rule: &str, comment: Value) -> Result<()> {
    let slot = grammar
        .get_mut("repository")
        .and_then(|repository| repository.get_mut(rule))
        .and_then(Value::as_object_mut)
        .with_context(|| format!("repository.{rule} is not an object"))?;
    if let Some(existing) = slot.get_mut("comment") {
        *existing = comment;
    } else {
        let mut rebuilt = serde_json::Map::new();
        rebuilt.insert("comment".to_owned(), comment);
        rebuilt.extend(std::mem::take(slot));
        *slot = rebuilt;
    }
    Ok(())
}

fn render_vscode_bigip(original: &str) -> Result<String> {
    let mut grammar: Value = serde_json::from_str(original).context("parsing BIG-IP grammar")?;

    set_rule(
        &mut grammar,
        "declaration",
        "match",
        Value::from(format!(
            r"^({})\s+([a-z0-9-]+)((?:\s+[a-z0-9-]+)*)",
            alternation(MODULES)?
        )),
    )?;
    let comment = provenance_comment(&grammar, "declaration", "tcl_bigip::conf_tokens::MODULES");
    set_rule_comment(&mut grammar, "declaration", comment)?;

    let mut patterns = Vec::new();
    for &(kind, token_type) in TYPED_REFERENCE_KINDS {
        let keys = keys_of(kind);
        if keys.is_empty() {
            bail!("the BIG-IP key table has no {token_type} key");
        }
        let scope = crate::editor_extensions::bigip_token_scope(token_type)
            .with_context(|| format!("no TextMate scope for the {token_type} token type"))?;
        patterns.push(json!({
            "match": format!(r"(?<=^|\s)({})\s+([^\s{{}}]+)", alternation(&keys)?),
            "captures": {
                "1": { "name": "variable.other.property.bigip" },
                "2": { "name": scope },
            },
        }));
    }
    set_rule(
        &mut grammar,
        "typed-object-reference",
        "patterns",
        Value::Array(patterns),
    )?;
    let comment = provenance_comment(
        &grammar,
        "typed-object-reference",
        "tcl_bigip::conf_tokens::KEYED_REFERENCES",
    );
    set_rule_comment(&mut grammar, "typed-object-reference", comment)?;

    let monitor_keys = keys_of(BigipTokenKind::Monitor);
    ensure!(
        !monitor_keys.is_empty(),
        "the BIG-IP key table has no monitor key"
    );
    set_rule(
        &mut grammar,
        "monitor-expression",
        "begin",
        Value::from(format!(
            r"(?<=^|\s)({})(?=\s|$)",
            alternation(&monitor_keys)?
        )),
    )?;
    let words = grammar["repository"]["monitor-expression"]["patterns"]
        .get_mut(0)
        .and_then(Value::as_object_mut)
        .context("monitor-expression.patterns[0] is not an object")?;
    ensure!(
        words.contains_key("match"),
        "monitor-expression.patterns[0] has no match"
    );
    words.insert(
        "match".to_owned(),
        Value::from(format!(
            r"(?<=^|\s)({})(?=\s|$)",
            alternation(&GRAMMAR_WORDS)?
        )),
    );
    let comment = provenance_comment(
        &grammar,
        "monitor-expression",
        "tcl_bigip::conf_tokens::KEYED_REFERENCES and \
         tcl_bigip::value::monitor_expression::GRAMMAR_WORDS",
    );
    set_rule_comment(&mut grammar, "monitor-expression", comment)?;
    to_pretty(&grammar)
}

/// A JSON grammar renderer: the committed file in, the projected file out.
type JsonRender = fn(&str) -> Result<String>;

/// Every generated file, `(repo-relative path, content)`.
fn generated_files() -> Result<Vec<(&'static str, String)>> {
    let root = repo_root();
    let apl = render_zed_apl()?;
    let bigip = render_zed_bigip();
    let mut out = vec![
        (ZED_APL, apl.clone()),
        (GRAMMAR_APL, apl),
        (ZED_BIGIP, bigip.clone()),
        (GRAMMAR_BIGIP, bigip),
    ];
    let json: [(&'static str, JsonRender); 2] = [
        (VSCODE_APL, render_vscode_apl),
        (VSCODE_BIGIP, render_vscode_bigip),
    ];
    for (rel, render) in json {
        let path = root.join(rel);
        let original =
            fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
        out.push((
            rel,
            render(&original).with_context(|| format!("rendering {rel}"))?,
        ));
    }
    Ok(out)
}

/// Write (or, with `check`, verify) every projected grammar file.
pub fn run(check: bool) -> Result<ExitCode> {
    let root = repo_root();
    let mut drift = Vec::new();
    for (rel, content) in generated_files()? {
        let path = root.join(rel);
        if check {
            let current =
                fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
            if current != content {
                drift.push(rel);
            }
        } else if write_if_changed(&path, &content)? {
            eprintln!("wrote {rel}");
        }
    }
    if check && !drift.is_empty() {
        eprintln!(
            "{} BIG-IP/APL grammar file(s) are stale — run `cargo xtask gen-bigip-grammars`:",
            drift.len()
        );
        for rel in &drift {
            eprintln!("  - {rel}");
        }
        return Ok(ExitCode::from(1));
    }
    if check {
        eprintln!("OK: the BIG-IP and APL editor grammars are in sync with their tcl-bigip owners.");
    }
    Ok(ExitCode::SUCCESS)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn committed_grammars_match_generated() {
        let root = repo_root();
        for (rel, content) in generated_files().expect("render") {
            let current = fs::read_to_string(root.join(rel))
                .unwrap_or_else(|error| panic!("reading {rel}: {error}"));
            assert_eq!(
                current, content,
                "{rel} is stale — run `cargo xtask gen-bigip-grammars`"
            );
        }
    }

    /// Rendering a rendered grammar changes nothing: the provenance note is
    /// appended once, not once per run.
    #[test]
    fn rendering_is_idempotent() {
        let root = repo_root();
        for (rel, render) in [
            (VSCODE_APL, render_vscode_apl as JsonRender),
            (VSCODE_BIGIP, render_vscode_bigip),
        ] {
            let original = fs::read_to_string(root.join(rel)).expect("read grammar");
            let once = render(&original).expect("render");
            assert_eq!(render(&once).expect("render again"), once, "{rel}");
        }
    }

    /// Each typed-reference rule carries the scope `package.json` maps the
    /// server's token type for that kind to.
    #[test]
    fn typed_reference_rules_use_the_semantic_token_scopes() {
        let rendered = fs::read_to_string(repo_root().join(VSCODE_BIGIP)).expect("read");
        for scope in [
            "entity.name.type.pool.bigip",
            "entity.name.type.profile.bigip",
            "entity.name.type.vlan.bigip",
        ] {
            assert!(rendered.contains(scope), "{scope}");
        }
        for &(_, token_type) in TYPED_REFERENCE_KINDS {
            assert!(
                crate::editor_extensions::bigip_token_scope(token_type).is_some(),
                "{token_type}"
            );
        }
    }

    /// Ground truth independent of the renderer: the owner words reach the
    /// shipped files.
    #[test]
    fn owner_words_reach_the_shipped_files() {
        let root = repo_root();
        let read = |rel: &str| fs::read_to_string(root.join(rel)).expect("read");
        let zed_apl = read(ZED_APL);
        assert!(zed_apl.contains("\"tcpprof\""), "{zed_apl}");
        assert!(zed_apl.contains("NonNegativeNumber"), "{zed_apl}");
        let zed_bigip = read(ZED_BIGIP);
        assert!(zed_bigip.contains("\"default-pool\""), "{zed_bigip}");
        let vscode_bigip = read(VSCODE_BIGIP);
        assert!(vscode_bigip.contains("api-protection"), "{vscode_bigip}");
        assert!(vscode_bigip.contains("last-hop-pool"), "{vscode_bigip}");
    }
}
