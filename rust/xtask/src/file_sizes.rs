//! `file-sizes` — holds every Rust source file to a line budget.
//!
//! A Rust file under `rust/` or `runtime/rust/` is at most [`LIMIT`] lines.
//! The files that were over the budget when the gate arrived are listed in
//! `docs/generated/rust-file-sizes.md`; the list only shrinks. A file over
//! the budget that is not on it fails the gate in both modes: split it
//! (`docs/work/file-split/README.md`). A listed file that now fits fails
//! `--check` until the ledger is regenerated, which drops it. A listed file
//! answers for its child modules too: split into modules, it stays listed
//! until every part fits.
//!
//! Outside the budget, as for the licence-header check: a generated file
//! (first line `// @generated` or `// Generated from`) and recorded test data
//! (a file under a `tests/data/` directory).

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use anyhow::{Context, Result};

/// The most lines a hand-written Rust file may have.
const LIMIT: usize = 2000;

const LEDGER: &str = "docs/generated/rust-file-sizes.md";
const ROOTS: &[&str] = &["rust", "runtime/rust"];
const GENERATED_MARKERS: &[&str] = &["// @generated", "// Generated from"];
const RECORDED_DATA: &str = "/tests/data/";
const ENTRY_PREFIX: &str = "- `";
const ENTRY_SUFFIX: &str = "`";

fn collect_rs_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let name = entry.file_name();
        let name = name.to_string_lossy();
        if path.is_dir() {
            if name != "target" && !name.starts_with('.') {
                collect_rs_files(&path, out);
            }
        } else if path.extension().is_some_and(|ext| ext == "rs") {
            out.push(path);
        }
    }
}

/// Whether `text` is over the budget. A generated file never is.
fn over_budget(text: &str) -> bool {
    !GENERATED_MARKERS
        .iter()
        .any(|marker| text.starts_with(marker))
        && text.lines().count() > LIMIT
}

/// Repo-relative paths of the hand-written files over the budget.
fn scan(root: &Path) -> BTreeSet<String> {
    let mut files = Vec::new();
    for tree in ROOTS {
        collect_rs_files(&root.join(tree), &mut files);
    }
    files
        .into_iter()
        .map(|path| {
            let relative = path.strip_prefix(root).unwrap_or(&path);
            (relative.to_string_lossy().replace('\\', "/"), path)
        })
        .filter(|(relative, path)| {
            !relative.contains(RECORDED_DATA)
                && std::fs::read_to_string(path).is_ok_and(|text| over_budget(&text))
        })
        .map(|(relative, _)| relative)
        .collect()
}

fn render(listed: &BTreeSet<String>) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# Rust files over the line budget\n");
    let _ = writeln!(
        out,
        "Generated by `cargo xtask file-sizes`; do not edit. A hand-written Rust file is at most \
         {LIMIT} lines. These {} files were over that when the gate arrived and they, or a module \
         split out of them, still are (`docs/work/file-split/README.md`). The list only shrinks: \
         the gate refuses a file over the budget that nothing here answers for.\n",
        listed.len()
    );
    for path in listed {
        let _ = writeln!(out, "{ENTRY_PREFIX}{path}{ENTRY_SUFFIX}");
    }
    out
}

fn parse(ledger: &str) -> BTreeSet<String> {
    ledger
        .lines()
        .filter_map(|line| line.strip_prefix(ENTRY_PREFIX)?.strip_suffix(ENTRY_SUFFIX))
        .map(str::to_owned)
        .collect()
}

/// Files over the budget that no ledger entry answers for, and entries with
/// nothing over the budget left. An entry answers for the file it names and
/// for that file's child modules, so a file split into modules stays listed
/// until every part fits.
fn problems(over: &BTreeSet<String>, listed: &BTreeSet<String>) -> (Vec<String>, Vec<String>) {
    let mut unlisted = Vec::new();
    let mut answering = BTreeSet::new();
    for path in over {
        let owner = crate::util::listed_module_owner(path, |candidate| listed.contains(candidate));
        if listed.contains(&owner) {
            answering.insert(owner);
        } else {
            unlisted.push(path.clone());
        }
    }
    (unlisted, listed.difference(&answering).cloned().collect())
}

/// Verify the budget. Without `check`, also drop ledger entries that now
/// fit, and write the ledger when there is none yet.
pub fn run(check: bool) -> Result<ExitCode> {
    let root = crate::util::repo_root();
    let ledger_path = root.join(LEDGER);
    let over = scan(&root);
    if !check && !ledger_path.exists() {
        crate::util::write_if_changed(&ledger_path, render(&over))?;
        println!("file-sizes: wrote {LEDGER} with {} file(s)", over.len());
        return Ok(ExitCode::SUCCESS);
    }
    let ledger =
        std::fs::read_to_string(&ledger_path).with_context(|| format!("reading {LEDGER}"))?;
    let listed = parse(&ledger);
    let (unlisted, fitting) = problems(&over, &listed);
    if !unlisted.is_empty() {
        eprintln!(
            "file-sizes: FAILED\n{} Rust file(s) are over {LIMIT} lines and not on {LEDGER}. \
             Split them (docs/work/file-split/README.md):",
            unlisted.len()
        );
        for path in &unlisted {
            eprintln!("  {path}");
        }
        return Ok(ExitCode::FAILURE);
    }
    if fitting.is_empty() {
        println!(
            "file-sizes: OK ({} listed file(s) still over {LIMIT} lines, none new)",
            listed.len()
        );
        return Ok(ExitCode::SUCCESS);
    }
    if check {
        eprintln!(
            "file-sizes: FAILED\n{} file(s) on {LEDGER} now fit the budget; run \
             `cargo xtask file-sizes` to drop them:",
            fitting.len()
        );
        for path in &fitting {
            eprintln!("  {path}");
        }
        return Ok(ExitCode::FAILURE);
    }
    let remaining: BTreeSet<String> = listed
        .difference(&fitting.iter().cloned().collect())
        .cloned()
        .collect();
    crate::util::write_if_changed(&ledger_path, render(&remaining))?;
    println!(
        "file-sizes: dropped {} file(s) that now fit; {} remain",
        fitting.len(),
        remaining.len()
    );
    Ok(ExitCode::SUCCESS)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn set(paths: &[&str]) -> BTreeSet<String> {
        paths.iter().map(|path| (*path).to_owned()).collect()
    }

    #[test]
    fn a_generated_file_is_outside_the_budget() {
        let long = "fn f() {}\n".repeat(LIMIT + 1);
        assert!(over_budget(&long));
        for marker in GENERATED_MARKERS {
            assert!(!over_budget(&format!("{marker} a table.\n{long}")));
        }
        assert!(!over_budget(&"fn f() {}\n".repeat(LIMIT)));
    }

    #[test]
    fn the_ledger_round_trips() {
        let listed = set(&["rust/a/src/lib.rs", "runtime/rust/src/interp.rs"]);
        assert_eq!(parse(&render(&listed)), listed);
    }

    #[test]
    fn a_new_large_file_and_a_listed_file_that_fits_are_told_apart() {
        let over = set(&["rust/a/src/big.rs", "rust/a/src/new.rs"]);
        let listed = set(&["rust/a/src/big.rs", "rust/a/src/split.rs"]);
        let (unlisted, fitting) = problems(&over, &listed);
        assert_eq!(unlisted, ["rust/a/src/new.rs"]);
        assert_eq!(fitting, ["rust/a/src/split.rs"]);

        // The listed file now fits, but one of its child modules does not yet.
        let over = set(&["rust/a/src/split/dispatch.rs"]);
        let (unlisted, fitting) = problems(&over, &listed);
        assert_eq!(unlisted, [] as [std::string::String; 0]);
        assert_eq!(fitting, ["rust/a/src/big.rs"]);
    }
}
