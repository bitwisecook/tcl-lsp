//! The committed probe outputs, each a snapshot of some columns of the rows.
//! A row test compares its own lines; an artefact test checks the rest.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use crate::rows::{Dialect, Fixture, Row};

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    /// `PROBE file dialect: [CODE Lline message]…`
    Bracket,
    /// `PROBE file dialect: [CODE Lline "text" message]…`
    BracketQuoted,
    /// `PROBE file dialect: CODE@text…`
    At,
    /// `FRAME file dialect word=… | def=… | hover=… | diag=…`
    Frame,
    /// `VAR file dialect at=… | def=… | refs=… | rename=… | hover=… | diag=…`
    Var,
    /// `file <TAB> interpreter <TAB> exit <TAB> output`
    Engines,
    /// `file <TAB> dialect <TAB> column <TAB> answer` for the analyser, the
    /// folder, its executed rewrites and the editor features
    Analysis,
    /// `file <TAB> dialect <TAB> CODE@line… <TAB> reviewed verdict`
    Verdicts,
    /// `D|O <TAB> area <TAB> file <TAB> dialect <TAB> diagnostics|rewrites`
    AreasHead,
    /// `same|differs… <TAB> area <TAB> file <TAB> dialect`
    RewritesExecuted,
}

pub struct Artefact {
    pub path: PathBuf,
    pub name: String,
    pub kind: Kind,
    /// Fixture areas the artefact covers.
    pub areas: BTreeSet<String>,
    header: Vec<String>,
    /// Committed body lines by fixture name (`area/file`).
    lines: BTreeMap<String, Vec<String>>,
    /// Committed lines that belong to no fixture of the covered areas.
    pub orphans: Vec<String>,
}

const ENGINES_HEADER: &str = "# Generated by `cargo xtask conformance`. fixture <TAB> interpreter <TAB> exit status <TAB> stdout and stderr, lines joined with \" ¶ \". tclshX.Y = C Tcl; jim = jimsh; vmX.Y = tclvm --tcl-version X.Y; rtX.Y = run_script --quiet --tcl-version X.Y.";
const ANALYSIS_HEADER: &str = "# Generated by `cargo xtask conformance`. fixture <TAB> dialect <TAB> column <TAB> answer. analyser = diagnostics as CODE@line; folder = rewrite codes; folded = C Tcl of the release run before and after the rewrites; editor = at a ;# CALL, ;# READ or ;# COMPLETE mark: word | definition | references | rename | hover, and the first completion labels at a ;# COMPLETE mark.";
const VERDICTS_HEADER: &str = "# Generated by `cargo xtask conformance`. fixture <TAB> dialect <TAB> analyser codes as CODE@line (\"-\" = none) <TAB> reviewed verdict. A verdict is kept while the codes it reviewed are unchanged; otherwise it reads \"review\".";
const AREAS_HEAD_HEADER: &str = "# Generated by `cargo xtask conformance`. D = analyser diagnostics (CODE@line:message), O = optimiser rewrites (codes), per area, fixture and dialect.";
const REWRITES_HEADER: &str = "# Generated by `cargo xtask conformance`. Whether C Tcl of the dialect's release runs each fixture the same before and after the optimiser's rewrites, from the fixture's own file name.";

fn header_for(kind: Kind) -> Vec<String> {
    match kind {
        Kind::Engines => vec![ENGINES_HEADER.to_owned()],
        Kind::Analysis => vec![ANALYSIS_HEADER.to_owned()],
        Kind::Verdicts => vec![VERDICTS_HEADER.to_owned()],
        Kind::AreasHead => vec![AREAS_HEAD_HEADER.to_owned()],
        Kind::RewritesExecuted => vec![REWRITES_HEADER.to_owned()],
        Kind::Bracket | Kind::BracketQuoted | Kind::At | Kind::Frame | Kind::Var => Vec::new(),
    }
}

/// The per-directory analyser views kept under their historical names.
const PROBE_VIEWS: &[(&str, &str, Kind)] = &[
    ("bodies.out", "bodies", Kind::At),
    ("dispatch.out", "dispatch", Kind::BracketQuoted),
    ("dynamic.out", "dynamic", Kind::Bracket),
    ("frames.out", "frames", Kind::Frame),
    ("tk.out", "tk", Kind::Bracket),
    ("variables.out", "variables", Kind::At),
    ("variables-flow.out", "variables-flow", Kind::Bracket),
    ("variables-lookup.out", "variables-lookup", Kind::Var),
    (
        "discriminating/analyser.out",
        "discriminating",
        Kind::Bracket,
    ),
    (
        "frames-semantics/analyser.out",
        "frames-semantics",
        Kind::Bracket,
    ),
    ("namespaces/analyser.out", "namespaces", Kind::Bracket),
];

/// The fourteen Tcl areas of the analyser and optimiser census.
const CENSUS_AREAS: &[&str] = &[
    "comments-continuations",
    "coroutines",
    "encodings-channels",
    "errors-returns",
    "event-loop",
    "exec-pipes",
    "interps",
    "regex-patterns",
    "special-variables",
    "tcl9-changes",
    "threads-subsystems",
    "traces",
    "unknown-autoload",
];

fn key_of(kind: Kind, line: &str, default_area: &str) -> Option<String> {
    let mut fields = line.split('\t');
    let (area, file) = match kind {
        Kind::Bracket | Kind::BracketQuoted | Kind::At | Kind::Frame | Kind::Var => {
            (default_area, line.split(' ').nth(1)?)
        }
        Kind::Engines | Kind::Analysis | Kind::Verdicts => (default_area, fields.next()?),
        Kind::AreasHead | Kind::RewritesExecuted => {
            fields.next()?;
            (fields.next()?, fields.next()?)
        }
    };
    Some(format!("{area}/{file}"))
}

impl Artefact {
    fn load(root: &Path, name: &str, kind: Kind, areas: BTreeSet<String>) -> Self {
        let path = root.join(name);
        let text = std::fs::read_to_string(&path).unwrap_or_default();
        let default_area = areas.iter().next().cloned().unwrap_or_default();
        let mut header = Vec::new();
        let mut lines: BTreeMap<String, Vec<String>> = BTreeMap::new();
        let mut orphans = Vec::new();
        for line in text.lines() {
            if line.starts_with('#') {
                header.push(line.to_owned());
            } else if line.trim().is_empty() {
            } else if let Some(key) = key_of(kind, line, &default_area) {
                lines.entry(key).or_default().push(line.to_owned());
            } else {
                orphans.push(line.to_owned());
            }
        }
        Self {
            path,
            name: name.to_owned(),
            kind,
            areas,
            header,
            lines,
            orphans,
        }
    }

    pub fn covers(&self, fixture: &Fixture) -> bool {
        self.areas.contains(&fixture.area)
    }

    pub fn committed(&self, fixture: &Fixture) -> &[String] {
        self.lines.get(&fixture.name()).map_or(&[], Vec::as_slice)
    }

    /// Lines for fixtures that do not exist, and a header that is not the
    /// generated one.
    pub fn structure_errors(&self, fixtures: &[Fixture]) -> Vec<String> {
        let known: BTreeSet<String> = fixtures
            .iter()
            .filter(|fixture| self.covers(fixture))
            .map(Fixture::name)
            .collect();
        let mut errors: Vec<String> = self
            .lines
            .keys()
            .filter(|key| !known.contains(*key))
            .map(|key| format!("{}: lines for unknown fixture {key}", self.name))
            .collect();
        errors.extend(
            self.orphans
                .iter()
                .map(|line| format!("{}: unattributed line {line:?}", self.name)),
        );
        if self.header != header_for(self.kind) {
            errors.push(format!(
                "{}: header differs from the generated one",
                self.name
            ));
        }
        errors
    }

    pub fn render(&self, fixture: &Fixture, row: &Row) -> Vec<String> {
        render(self.kind, fixture, row, self.committed(fixture))
    }

    pub fn write(&self, fixtures: &[Fixture], rendered: &BTreeMap<String, Vec<String>>) {
        let mut text = String::new();
        for line in header_for(self.kind) {
            let _ = writeln!(text, "{line}");
        }
        for fixture in fixtures.iter().filter(|fixture| self.covers(fixture)) {
            let name = fixture.name();
            let lines = rendered
                .get(&name)
                .or_else(|| self.lines.get(&name))
                .map_or(&[][..], Vec::as_slice);
            for line in lines {
                let _ = writeln!(text, "{line}");
            }
        }
        std::fs::write(&self.path, text)
            .unwrap_or_else(|error| panic!("{}: {error}", self.path.display()));
    }
}

pub fn catalogue(root: &Path, fixtures: &[Fixture]) -> Vec<Artefact> {
    let areas: BTreeSet<String> = fixtures.iter().map(|f| f.area.clone()).collect();
    let mut artefacts: Vec<Artefact> = PROBE_VIEWS
        .iter()
        .map(|&(name, area, kind)| {
            Artefact::load(root, name, kind, BTreeSet::from([area.to_owned()]))
        })
        .collect();
    for area in &areas {
        // `expressions/engines.tsv` holds item 28's `exprs.txt` vector table.
        let engines = if area == "expressions" {
            format!("{area}/fixture-engines.tsv")
        } else {
            format!("{area}/engines.tsv")
        };
        artefacts.push(Artefact::load(
            root,
            &engines,
            Kind::Engines,
            BTreeSet::from([area.clone()]),
        ));
        artefacts.push(Artefact::load(
            root,
            &format!("{area}/analysis.tsv"),
            Kind::Analysis,
            BTreeSet::from([area.clone()]),
        ));
        let verdicts = format!("{area}/analyser-mcp.out");
        if root.join(&verdicts).is_file() {
            artefacts.push(Artefact::load(
                root,
                &verdicts,
                Kind::Verdicts,
                BTreeSet::from([area.clone()]),
            ));
        }
    }
    let census: BTreeSet<String> = CENSUS_AREAS.iter().map(|&area| area.to_owned()).collect();
    artefacts.push(Artefact::load(
        root,
        "tcl-areas-head/analyser-optimiser-head.tsv",
        Kind::AreasHead,
        census.clone(),
    ));
    artefacts.push(Artefact::load(
        root,
        "tcl-areas-head/rewrites-executed.tsv",
        Kind::RewritesExecuted,
        census,
    ));
    artefacts
}

fn list<T: std::fmt::Debug>(items: &[T]) -> String {
    format!("{items:?}")
}

fn render(kind: Kind, fixture: &Fixture, row: &Row, committed: &[String]) -> Vec<String> {
    let file = &fixture.file;
    if kind == Kind::Engines {
        return row
            .engines
            .iter()
            .map(|(interpreter, outcome)| {
                format!(
                    "{file}\t{interpreter}\t{}\t{}",
                    outcome.exit, outcome.output
                )
            })
            .collect();
    }
    let mut out = Vec::new();
    for dialect in &row.dialects {
        match kind {
            Kind::Analysis => analysis_lines(file, dialect, &mut out),
            Kind::Bracket | Kind::BracketQuoted | Kind::At => {
                out.push(probe_line(kind, file, dialect));
            }
            Kind::Frame | Kind::Var => editor_lines(kind, file, dialect, &mut out),
            Kind::Verdicts => out.push(verdict_line(file, dialect, committed)),
            Kind::AreasHead => {
                let (area, name) = (&fixture.area, dialect.name);
                let diagnostics: Vec<String> = dialect
                    .diagnostics
                    .iter()
                    .map(|d| format!("{}@{}:{}", d.code, d.line, d.message))
                    .collect();
                out.push(format!(
                    "D\t{area}\t{file}\t{name}\t{}",
                    diagnostics.join(" | ")
                ));
                out.push(format!(
                    "O\t{area}\t{file}\t{name}\t{}",
                    dialect.folds.join(",")
                ));
            }
            Kind::RewritesExecuted => {
                if let Some(result) = &dialect.folded_execution {
                    out.push(format!(
                        "{result}\t{}\t{file}\t{}",
                        fixture.area, dialect.name
                    ));
                }
            }
            Kind::Engines => unreachable!("engine lines are rendered above"),
        }
    }
    out
}

pub fn assert_engine_row_snapshot() {
    let fixture = Fixture {
        path: PathBuf::new(),
        area: "errors-returns".to_owned(),
        file: "fixture.tcl".to_owned(),
    };
    let row = Row {
        engines: vec![(
            "tclsh8.6".to_owned(),
            crate::engines::Outcome {
                exit: "1".to_owned(),
                output: "one ¶ two".to_owned(),
            },
        )],
        dialects: Vec::new(),
    };
    let lines = render(Kind::Engines, &fixture, &row, &[]);
    insta::assert_snapshot!(lines.join("\n"), @"fixture.tcl\ttclsh8.6\t1\tone ¶ two");
}

fn analysis_lines(file: &str, dialect: &Dialect, out: &mut Vec<String>) {
    let name = dialect.name;
    let codes: Vec<String> = dialect
        .diagnostics
        .iter()
        .map(|d| format!("{}@{}", d.code, d.line))
        .collect();
    out.push(format!("{file}\t{name}\tanalyser\t{}", codes.join(" ")));
    out.push(format!(
        "{file}\t{name}\tfolder\t{}",
        dialect.folds.join(",")
    ));
    if let Some(result) = &dialect.folded_execution {
        out.push(format!("{file}\t{name}\tfolded\t{result}"));
    }
    for answers in &dialect.editor {
        let definition: Vec<&String> = answers
            .definition
            .iter()
            .map(|(_, position, _)| position)
            .collect();
        let mut row = format!(
            "{file}\t{name}\teditor\t{} | def={} | refs={} | rename={} | hover={}",
            answers.word,
            list(&definition),
            list(&answers.references),
            list(&answers.rename),
            answers.hover
        );
        if let Some(completion) = &answers.completion {
            row.push_str(" | complete=");
            row.push_str(&list(completion));
        }
        out.push(row);
    }
}

fn probe_line(kind: Kind, file: &str, dialect: &Dialect) -> String {
    let mut codes: Vec<String> = dialect
        .diagnostics
        .iter()
        .map(|d| match kind {
            Kind::At => {
                let text: String = first_line(&d.text).chars().take(12).collect();
                format!("{}@{text}", d.code)
            }
            Kind::BracketQuoted => {
                let text: String = first_line(&d.text).chars().take(14).collect();
                let message: String = d.message.chars().take(70).collect();
                format!("[{} L{} {text:?} {message}]", d.code, d.line)
            }
            _ => {
                let message: String = d.message.chars().take(70).collect();
                format!("[{} L{} {message}]", d.code, d.line)
            }
        })
        .collect();
    codes.sort();
    format!("PROBE {file} {}: {}", dialect.name, codes.join(" "))
}

fn editor_lines(kind: Kind, file: &str, dialect: &Dialect, out: &mut Vec<String>) {
    let name = dialect.name;
    for answers in &dialect.editor {
        let definition: Vec<String> = answers
            .definition
            .iter()
            .map(|(line, position, text)| {
                if kind == Kind::Frame {
                    format!("L{line}:{text}")
                } else {
                    position.clone()
                }
            })
            .collect();
        out.push(if kind == Kind::Frame {
            format!(
                "FRAME {file} {name} word={} | def={} | hover={} | diag={}",
                answers.word,
                list(&definition),
                answers.hover,
                list(&answers.diagnostics)
            )
        } else {
            let mut codes: Vec<String> = dialect
                .diagnostics
                .iter()
                .map(|d| format!("{}@L{}", d.code, d.line))
                .collect();
            codes.sort();
            format!(
                "VAR {file} {name} at={:?} | def={} | refs={} | rename={} | hover={} | diag={}",
                answers.at,
                list(&definition),
                list(&answers.references),
                list(&answers.rename),
                answers.hover,
                list(&codes)
            )
        });
    }
}

/// A reviewed verdict holds while the codes it reviewed are unchanged.
fn verdict_line(file: &str, dialect: &Dialect, committed: &[String]) -> String {
    let name = dialect.name;
    let codes = if dialect.diagnostics.is_empty() {
        "-".to_owned()
    } else {
        dialect
            .diagnostics
            .iter()
            .map(|d| format!("{}@{}", d.code, d.line))
            .collect::<Vec<_>>()
            .join(" ")
    };
    let verdict = committed
        .iter()
        .map(|line| line.split('\t').collect::<Vec<_>>())
        .find(|fields| {
            fields.get(1) == Some(&name)
                && fields.get(2).map(|c| strip_details(c)).as_ref() == Some(&codes)
        })
        .and_then(|fields| fields.get(3).map(|v| (*v).to_owned()))
        .filter(|verdict| !verdict.is_empty())
        .unwrap_or_else(|| "review".to_owned());
    format!("{file}\t{name}\t{codes}\t{verdict}")
}

fn first_line(text: &str) -> &str {
    text.split('\n').next().unwrap_or_default()
}

/// `W214@2(n2,op) W210@10(y)` reviewed as `W214@2 W210@10`.
fn strip_details(codes: &str) -> String {
    codes
        .split(' ')
        .map(|code| code.split('(').next().unwrap_or(code))
        .collect::<Vec<_>>()
        .join(" ")
}
