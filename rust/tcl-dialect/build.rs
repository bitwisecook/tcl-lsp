use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

const MANIFEST: &str = "data/reference-toolchains.tsv";
const RELEASES: [&str; 5] = ["8.4", "8.5", "8.6", "9.0", "9.1"];

fn main() {
    println!("cargo:rerun-if-changed={MANIFEST}");

    let manifest = fs::read_to_string(MANIFEST).expect("read Tcl reference-toolchain manifest");
    let rows: Vec<_> = manifest
        .lines()
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .map(|line| {
            let fields: Vec<_> = line.split('\t').collect();
            assert_eq!(
                fields.len(),
                3,
                "Tcl reference-toolchain rows have exactly three fields"
            );
            assert!(
                fields.iter().all(|field| !field.is_empty()),
                "Tcl reference-toolchain fields are non-empty"
            );
            (fields[0], fields[1], fields[2])
        })
        .collect();

    assert_eq!(rows.len(), RELEASES.len(), "one row per Tcl release line");
    for (row, expected) in rows.iter().zip(RELEASES) {
        assert_eq!(row.0, expected, "Tcl release rows stay in enum order");
    }

    let mut generated = String::from(
        "// @generated by rust/tcl-dialect/build.rs from data/reference-toolchains.tsv\n",
    );
    write!(
        generated,
        "pub(crate) const REFERENCE_PATCHLEVELS: [&str; {}] = [",
        rows.len()
    )
    .expect("write generated patchlevel table");
    for (_, patchlevel, _) in &rows {
        write!(generated, "{patchlevel:?},").expect("write generated patchlevel");
    }
    generated.push_str("];\n");
    write!(
        generated,
        "pub(crate) const REFERENCE_SOURCE_TAGS: [&str; {}] = [",
        rows.len()
    )
    .expect("write generated source-tag table");
    for (_, _, source_tag) in &rows {
        write!(generated, "{source_tag:?},").expect("write generated source tag");
    }
    generated.push_str("];\n");

    let output = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR is set"))
        .join("reference_toolchains.rs");
    fs::write(output, generated).expect("write generated Tcl reference-toolchain constants");
}
