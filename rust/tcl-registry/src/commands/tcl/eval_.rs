//! `eval` — evaluate a Tcl script dynamically.

use crate::prelude::*;

/// `eval`'s script body can do literally anything once evaluated — set
/// variables, open files, spawn processes — none of which the compiler
/// can enumerate from the raw argument words alone, so this deliberately
/// declares `Unknown`/no-reads/no-writes as an "unknowable statically"
/// placeholder rather than asserting a specific effect the command
/// doesn't actually have. `apply`'s spec cites this exact idiom (its
/// lambda body is equally opaque) back to this constant.
const SIDE_EFFECTS: &[SideEffect] = &[SideEffect {
    target: SideEffectTarget::Unknown,
    reads: false,
    writes: false,
    connection_side: ConnectionSide::None,
    dialects: None,
}];

/// `eval arg ?arg ...?` — synopsis, arity, and return-value wording
/// ("returns the result of that evaluation (or any error generated by
/// it)") are byte-for-byte identical across the fetched Tcl 8.4, 8.5,
/// 8.6, 9.0, and 9.1 manpages: no option/flag was ever added or removed,
/// so this is the command's only form, unrestricted by dialect or
/// version. The DESCRIPTION prose itself has two textual (not
/// behavioural) deltas across versions: (1) 8.5+ manpages add usage
/// *advice* to prefer `{*}$script` over `eval` for the common
/// word-list-expansion case, since `{*}` itself didn't exist before 8.5;
/// (2) 9.0 and 9.1 manpages append one clarifying sentence spelling out
/// that `eval [list $a $b $c]` and `$a $b $c` are equivalent — the same
/// list-quoting fact 8.4/8.5/8.6 already state, just less explicitly, not
/// a new behaviour introduced in 9.0. Neither delta changes eval's
/// grammar, arity, or semantics, so both are reflected as plain prose in
/// the hover snippet below rather than as dialect gates here.
const FORMS: &[FormSpec] = &[FormSpec {
    kind: FormKind::Default,
    synopsis: "eval arg ?arg ...?",
    dialects: None,
}];

/// Command spec for `eval`.
pub fn spec() -> CommandSpec {
    CommandSpec {
        name: "eval",
        dialects: Some(DialectSet::ALL_TCL.union(DialectSet::IRULES)),
        traits: Traits::NOT_PROC_FACTORY
            | Traits::BYTE_COMPILED
            | Traits::LANGUAGE_KEYWORD
            | Traits::CREATES_BARRIER
            | Traits::EVALUATES_CODE
            | Traits::TAINT_SINK
            | Traits::CREATES_DYNAMIC_BARRIER
            | Traits::DYNAMIC_EVAL_BODY
            | Traits::SCRIPT_CONCATENATES_ARGS,
        arity: Arity::at_least(1),
        arg_roles: &[(0, ArgRole::Body)],
        // `eval` concatenates its args and runs the result **in the calling
        // frame** — no level word, no frame shift.  A script it cannot read
        // statically (`eval $body`) can therefore create, read, or destroy
        // any local of the frame the `eval` is written in (tclsh 9.0.4 /
        // 8.6.14: `proc f {b} {set helper 42; eval $b}` called with
        // `{set helper}` returns `42`, while the same body under
        // `uplevel 1 $b` raises `can't read "helper"`).
        frame_effect: Some(FrameEffectSpec {
            level_word: FrameLevelWord::None,
            layout: FrameArgLayout::ScriptInCurrentFrame,
        }),
        lowering_hook: Some(crate::hooks::LoweringHookId::Eval),
        return_type: Some(TclType::String),
        hover: Some(HoverSnippet {
            summary: "Evaluate one or more arguments as a Tcl script.",
            synopsis: &["eval arg ?arg ...?"],
            snippet: "Concatenates all of its arguments in the same fashion as `concat`, then passes the result to the Tcl interpreter recursively as a script, evaluated in the caller's own variable/procedure context — unlike `uplevel`, `eval` never changes stack frame.\n\nBecause the `list` command quotes words so that they are not further expanded by `eval`, `eval [list $a $b $c]` and `$a $b $c` are equivalent for any values of $a, $b, and $c; this is what makes it safe to rebuild and re-run a command from a `list`-built value.\n\n**Security**: any argument built from unsanitised input becomes arbitrary code once concatenated and evaluated — `eval` is a taint sink. In the common case of expanding a pre-built word list, prefer `{*}$cmdList` (Tcl 8.5+) instead: it is less general than `eval` but, since it never re-parses the words as script text, far easier to keep safe.",
            source: "Tcl eval(n)",
            examples: "set script {puts \"logging now\"}\neval $script\n\n# Safe: list-quoted words are not re-split, so this is equivalent to\n# calling the command directly.\nset cmd [list string index $line 0]\neval $cmd\n\n# Prefer {*} to expand a pre-built word list instead (Tcl 8.5+):\nset argsList [list -nocase $pattern $line]\nset matched [string match {*}$argsList]",
            return_value: "The result of evaluating the concatenated script, or the error it raises — propagated as eval's own result, including any -errorinfo/-errorcode/-level the script's error carried.",
        }),
        // A `LIST_CANONICAL` value preserves element
        // boundaries and suppresses T100.
        taint_sink_safe_colour: Some(TaintColour::LIST_CANONICAL),
        forms: FORMS,
        side_effects: SIDE_EFFECTS,
        xc_translatable: Some(false),
        ..CommandSpec::DEFAULT
    }
}
