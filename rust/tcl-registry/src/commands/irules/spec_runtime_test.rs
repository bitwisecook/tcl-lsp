//! Runtime construction + validation of every iRules command spec.
//!
//! `IRULES_SPECS` is a compile-time `const` array, so each `const fn spec()`
//! body is evaluated by the compiler and shows no *runtime* coverage. Calling
//! every constructor here in a non-const context exercises them at runtime,
//! and the assertions make it a genuine test: every spec is well-formed
//! (non-empty name) and the runtime-built set matches the compile-time array.

use crate::spec::CommandSpec;

#[test]
fn every_irules_spec_constructs_at_runtime() {
    let specs: Vec<CommandSpec> = runtime_specs();
    assert_eq!(
        specs.len(),
        super::IRULES_SPECS.len(),
        "runtime spec set must match the compile-time IRULES_SPECS array"
    );
    for s in &specs {
        assert!(!s.name.is_empty(), "iRules command spec has an empty name");
    }
}

