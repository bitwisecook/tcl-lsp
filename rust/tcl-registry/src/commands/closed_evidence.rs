//! The rows whose purity domains their implementation's source closes
//! (issue #1712).
//!
//! [`table::CLOSED`] is generated by `scripts/dev/gen_closed_evidence.py`
//! from the evidence in `tests/data/command_evidence`: for each row, the
//! release windows at which the procedure that implements it reaches no
//! world-touching interface, runs no script, and completes only normally or
//! with an error. A command group's collector applies it, so every consumer
//! of the row reads the same complete knowledge; the integration test
//! `command_evidence::complete_rows_match_the_c_evidence` holds every closed
//! claim to its evidence line.

mod table;

use crate::completion::CompletionDescriptor;
use crate::dispatch_stability::{DispatchDependencies, DispatchDependencyDescriptor};
use crate::knowledge::Knowledge;
use crate::purity::closed_domains;
use crate::spec::{CommandSpec, SubCommand};
use crate::state_transition::StateTransitionDescriptor;
use std::collections::HashMap;
use std::sync::{Mutex, OnceLock};
use table::CLOSED;
use tcl_dialect::model::SpecSurface;

fn closed_surfaces(group: &str, command: &str, subcommand: &str) -> Option<&'static [SpecSurface]> {
    CLOSED
        .iter()
        .find(|&&(g, c, s, _)| g == group && c == command && s == subcommand)
        .map(|&(_, _, _, surfaces)| surfaces)
}

/// The closed completion: an authored contract that already admits only a
/// normal completion or an error is kept, as it is at least as precise.
fn closed_completion(
    authored: Knowledge<CompletionDescriptor>,
    closed: Knowledge<CompletionDescriptor>,
) -> Knowledge<CompletionDescriptor> {
    match (authored.stated(), closed) {
        (Some(descriptor), Knowledge::Complete(_, surfaces))
            if crate::purity::completes_normally_or_raises(descriptor) =>
        {
            Knowledge::Complete(descriptor, surfaces)
        }
        _ => closed,
    }
}

fn close_command(spec: &mut CommandSpec, surfaces: &'static [SpecSurface]) {
    let (side_effects, world_effects, completion, result_stability) = closed_domains(surfaces);
    spec.side_effects = side_effects;
    spec.world_effects = world_effects;
    spec.completion = closed_completion(spec.completion, completion);
    spec.result_stability = result_stability;
    spec.state_transitions = spec.state_transitions.stated().map_or(
        crate::knowledge::Knowledge::Complete(StateTransitionDescriptor::EMPTY, surfaces),
        crate::knowledge::Knowledge::Partial,
    );
    spec.dispatch_dependencies =
        spec.dispatch_dependencies
            .or(Some(DispatchDependencyDescriptor::replace(
                DispatchDependencies::NONE,
            )));
}

fn close_subcommand(sub: &mut SubCommand, surfaces: &'static [SpecSurface]) {
    let (side_effects, world_effects, completion, result_stability) = closed_domains(surfaces);
    sub.side_effects = side_effects;
    sub.world_effects = world_effects;
    sub.completion = closed_completion(sub.completion, completion);
    sub.result_stability = result_stability;
    sub.state_transitions = sub.state_transitions.stated().map_or(
        crate::knowledge::Knowledge::Complete(StateTransitionDescriptor::EMPTY, surfaces),
        crate::knowledge::Knowledge::Partial,
    );
    sub.dispatch_dependencies =
        sub.dispatch_dependencies
            .or(Some(DispatchDependencyDescriptor::replace(
                DispatchDependencies::NONE,
            )));
}

/// The subcommand table of `command` with each evidenced subcommand closed.
/// A table is patched once and shared, as the shipped tables are static.
fn closed_subcommands(
    group: &str,
    command: &str,
    subs: &'static [SubCommand],
) -> &'static [SubCommand] {
    type Patched = Mutex<HashMap<(usize, usize), &'static [SubCommand]>>;
    static PATCHED: OnceLock<Patched> = OnceLock::new();
    let key = (subs.as_ptr() as usize, subs.len());
    let mut patched = PATCHED
        .get_or_init(Mutex::default)
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner);
    patched.entry(key).or_insert_with(|| {
        let mut table = subs.to_vec();
        for sub in &mut table {
            if let Some(surfaces) = closed_surfaces(group, command, sub.name) {
                close_subcommand(sub, surfaces);
            }
        }
        table.leak()
    })
}

/// Close every row of `group` that its source evidence closes.
pub(crate) fn apply(group: &str, specs: &mut [CommandSpec]) {
    for spec in specs {
        if let Some(surfaces) = closed_surfaces(group, spec.name, "") {
            close_command(spec, surfaces);
        }
        let closes_a_subcommand = CLOSED
            .iter()
            .any(|&(g, c, s, _)| g == group && c == spec.name && !s.is_empty());
        if closes_a_subcommand {
            spec.subcommands = closed_subcommands(group, spec.name, spec.subcommands);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::result_stability::ResultStability;
    use crate::side_effects::SideEffect;
    use crate::world_effect::WorldEffectDescriptor;

    /// The authored facts of a row that its closed domains would override:
    /// an effect, a world access, a non-normal completion, or a result
    /// dependency the row states.
    fn overridden_facts(
        side_effects: Knowledge<&'static [SideEffect]>,
        world_effects: Knowledge<WorldEffectDescriptor>,
        completion: Knowledge<CompletionDescriptor>,
        result_stability: Knowledge<ResultStability>,
    ) -> Vec<String> {
        let mut overridden = Vec::new();
        if !side_effects.lower_bound().is_empty() {
            overridden.push(format!("side_effects {:?}", side_effects.lower_bound()));
        }
        if let Some(world) = world_effects.stated()
            && !world.is_effect_free()
        {
            overridden.push(format!("world_effects {:?}", world.static_footprint));
        }
        if let Some(descriptor) = completion.stated()
            && !crate::purity::completes_normally_or_raises(descriptor)
        {
            overridden.push(format!("completion {:?}", descriptor.codes));
        }
        if let Some(stability) = result_stability.stated()
            && stability != ResultStability::ReferentiallyTransparent
        {
            overridden.push(format!("result_stability {stability:?}"));
        }
        overridden
    }

    fn authored(group: &str) -> Vec<CommandSpec> {
        match group {
            "tcl" => crate::commands::tcl::authored_tcl_command_specs(),
            "tcllib" => crate::commands::tcllib::authored_tcllib_command_specs(),
            other => panic!("no collector for `{other}`"),
        }
    }

    /// The evidence only closes what a row's own authored facts leave open:
    /// a closed row never overrides an effect, a non-normal completion or a
    /// result dependency the row states.
    #[test]
    fn no_closed_row_overrides_an_authored_fact() {
        let mut contradictions = Vec::new();
        let mut found = std::collections::HashSet::new();
        for group in ["tcl", "tcllib"] {
            for spec in authored(group) {
                if closed_surfaces(group, spec.name, "").is_some() {
                    found.insert((group, spec.name, ""));
                    let overridden = overridden_facts(
                        spec.side_effects,
                        spec.world_effects,
                        spec.completion,
                        spec.result_stability,
                    );
                    if !overridden.is_empty() {
                        contradictions.push(format!("{}: {overridden:?}", spec.name));
                    }
                }
                for sub in spec.subcommands {
                    if closed_surfaces(group, spec.name, sub.name).is_none() {
                        continue;
                    }
                    found.insert((group, spec.name, sub.name));
                    // A subcommand's evidence replaces the effects it would
                    // inherit, which are its ensemble's union over every
                    // subcommand; only its own stated facts may contradict it.
                    let overridden = overridden_facts(
                        sub.side_effects,
                        sub.world_effects,
                        sub.completion,
                        sub.result_stability,
                    );
                    if !overridden.is_empty() {
                        contradictions.push(format!("{} {}: {overridden:?}", spec.name, sub.name));
                    }
                }
            }
        }
        let unmatched: Vec<_> = CLOSED
            .iter()
            .filter(|&&(g, c, s, _)| !found.contains(&(g, c, s)))
            .collect();
        assert!(
            unmatched.is_empty(),
            "evidenced rows with no shipped row: {unmatched:?}"
        );
        assert!(contradictions.is_empty(), "{contradictions:#?}");
    }
}
