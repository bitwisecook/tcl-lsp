//! POSIX shell words for generated venv source, separate from Tcl list values.

use std::path::{Path, PathBuf};

use crate::errors::TclPkgError;

struct PosixLiteral(String);

impl PosixLiteral {
    fn text(value: &str) -> Result<Self, TclPkgError> {
        if value.as_bytes().contains(&0) {
            return Err(super::venv_error(
                "POSIX shell source cannot contain NUL",
                None,
            ));
        }
        Ok(Self(tcl_syntax::posix_shell::quote_literal(value)))
    }

    fn path_component(value: &Path) -> Result<Self, TclPkgError> {
        let value = value.to_str().ok_or_else(|| {
            super::venv_error(
                "path has no Unicode POSIX PATH-component representation",
                None,
            )
        })?;
        if value.contains(':') {
            return Err(super::venv_error(
                "POSIX PATH cannot represent a component containing ':'",
                None,
            ));
        }
        Self::text(value)
    }

    fn path(value: &Path) -> Result<Self, TclPkgError> {
        Self::text(value.to_str().ok_or_else(|| {
            super::venv_error(
                "path has no Unicode POSIX shell-source representation",
                None,
            )
        })?)
    }
}

pub(super) fn selected_executable(tclsh: &Path) -> Result<PathBuf, TclPkgError> {
    // Retain the actual selection cwd for a relative PATH entry. Following
    // symlinks would change the selected executable's original path spelling.
    let selected = if tclsh.is_absolute() {
        tclsh.to_path_buf()
    } else {
        std::env::current_dir()
            .map_err(|error| {
                super::venv_error(
                    format!("cannot retain interpreter selection directory: {error}"),
                    None,
                )
            })?
            .join(tclsh)
    };
    PosixLiteral::path(&selected)?;
    Ok(selected)
}

pub(super) fn wrapper(tclsh: &Path) -> Result<String, TclPkgError> {
    let executable = PosixLiteral::path(tclsh)?;
    Ok(format!(
        "#!/bin/sh\n# Auto-generated by tclpkg — do not edit.\nVENV=\"$(cd \"$(dirname \"$0\")/..\" && pwd)\"\n: \"${{TCLLIBPATH:=}}\"\nexport TCLLIBPATH=\"$VENV/lib${{TCLLIBPATH:+ $TCLLIBPATH}}\"\nexport TCL_VENV=\"$VENV\"\nexec {} \"$@\"\n",
        executable.0,
    ))
}

/// Retain shell variable values and presence; export attributes remain separate.
pub(super) fn activation(venv: &Path, prompt: &str) -> Result<String, TclPkgError> {
    let root = PosixLiteral::path(venv)?;
    let bin = PosixLiteral::path_component(&venv.join("bin"))?;
    let prefix = super::prepare_tcllibpath(&venv.join("lib"), None)?;
    let prefix = PosixLiteral::text(prefix.to_str().ok_or_else(|| {
        super::venv_error(
            "TCLLIBPATH source has no Unicode shell-source representation",
            None,
        )
    })?)?;
    let prompt = PosixLiteral::text(&format!("({prompt}) "))?;
    Ok(format!(
        r#"# Auto-generated by tclpkg - source this file, do not execute.

deactivate () {{
    if [ "${{_TCLPKG_POSIX_VENV_ACTIVE-}}" != x ]; then return; fi
    if [ "${{_OLD_TCL_VENV_PATH_SET+x}}${{_OLD_TCL_VENV_PATH+x}}${{_OLD_TCL_VENV_TCLLIBPATH_SET+x}}${{_OLD_TCL_VENV_TCLLIBPATH+x}}${{_OLD_TCL_VENV_PS1_SET+x}}${{_OLD_TCL_VENV_PS1+x}}${{_OLD_TCL_VENV_ROOT_SET+x}}${{_OLD_TCL_VENV_ROOT+x}}" != xxxxxxxx ]; then
        printf '%s\n' 'tclpkg: incomplete venv activation state' >&2
        return 1
    fi
    case "${{_OLD_TCL_VENV_PATH_SET-}}" in
        ''|x) ;;
        *) printf '%s\n' 'tclpkg: invalid venv presence metadata' >&2; return 1 ;;
    esac
    case "${{_OLD_TCL_VENV_TCLLIBPATH_SET-}}" in
        ''|x) ;;
        *) printf '%s\n' 'tclpkg: invalid venv presence metadata' >&2; return 1 ;;
    esac
    case "${{_OLD_TCL_VENV_PS1_SET-}}" in
        ''|x) ;;
        *) printf '%s\n' 'tclpkg: invalid venv presence metadata' >&2; return 1 ;;
    esac
    case "${{_OLD_TCL_VENV_ROOT_SET-}}" in
        ''|x) ;;
        *) printf '%s\n' 'tclpkg: invalid venv presence metadata' >&2; return 1 ;;
    esac
    if [ "${{_OLD_TCL_VENV_PATH_SET-}}" = x ]; then
        PATH="${{_OLD_TCL_VENV_PATH-}}"
        export PATH
    else
        unset PATH
    fi
    unset _OLD_TCL_VENV_PATH _OLD_TCL_VENV_PATH_SET
    if [ "${{_OLD_TCL_VENV_TCLLIBPATH_SET-}}" = x ]; then
        TCLLIBPATH="${{_OLD_TCL_VENV_TCLLIBPATH-}}"
        export TCLLIBPATH
    else
        unset TCLLIBPATH
    fi
    unset _OLD_TCL_VENV_TCLLIBPATH _OLD_TCL_VENV_TCLLIBPATH_SET
    if [ "${{_OLD_TCL_VENV_PS1_SET-}}" = x ]; then
        PS1="${{_OLD_TCL_VENV_PS1-}}"
        export PS1
    else
        unset PS1
    fi
    unset _OLD_TCL_VENV_PS1 _OLD_TCL_VENV_PS1_SET
    if [ "${{_OLD_TCL_VENV_ROOT_SET-}}" = x ]; then
        TCL_VENV="${{_OLD_TCL_VENV_ROOT-}}"
        export TCL_VENV
    else
        unset TCL_VENV
    fi
    unset _OLD_TCL_VENV_ROOT _OLD_TCL_VENV_ROOT_SET
    unset _TCLPKG_POSIX_VENV_ACTIVE
}}

if [ "${{_TCLPKG_POSIX_VENV_ACTIVE-}}" = x ]; then
    if [ "${{_OLD_TCL_VENV_PATH_SET+x}}${{_OLD_TCL_VENV_PATH+x}}${{_OLD_TCL_VENV_TCLLIBPATH_SET+x}}${{_OLD_TCL_VENV_TCLLIBPATH+x}}${{_OLD_TCL_VENV_PS1_SET+x}}${{_OLD_TCL_VENV_PS1+x}}${{_OLD_TCL_VENV_ROOT_SET+x}}${{_OLD_TCL_VENV_ROOT+x}}" != xxxxxxxx ]; then
        printf '%s\n' 'tclpkg: incomplete venv activation state' >&2
        return 1
    fi
    case "${{_OLD_TCL_VENV_PATH_SET-}}" in
        ''|x) ;;
        *) printf '%s\n' 'tclpkg: invalid venv presence metadata' >&2; return 1 ;;
    esac
    case "${{_OLD_TCL_VENV_TCLLIBPATH_SET-}}" in
        ''|x) ;;
        *) printf '%s\n' 'tclpkg: invalid venv presence metadata' >&2; return 1 ;;
    esac
    case "${{_OLD_TCL_VENV_PS1_SET-}}" in
        ''|x) ;;
        *) printf '%s\n' 'tclpkg: invalid venv presence metadata' >&2; return 1 ;;
    esac
    case "${{_OLD_TCL_VENV_ROOT_SET-}}" in
        ''|x) ;;
        *) printf '%s\n' 'tclpkg: invalid venv presence metadata' >&2; return 1 ;;
    esac
else
    _OLD_TCL_VENV_PATH_SET=${{PATH+x}}
    _OLD_TCL_VENV_PATH="${{PATH-}}"
    _OLD_TCL_VENV_TCLLIBPATH_SET=${{TCLLIBPATH+x}}
    _OLD_TCL_VENV_TCLLIBPATH="${{TCLLIBPATH-}}"
    _OLD_TCL_VENV_PS1_SET=${{PS1+x}}
    _OLD_TCL_VENV_PS1="${{PS1-}}"
    _OLD_TCL_VENV_ROOT_SET=${{TCL_VENV+x}}
    _OLD_TCL_VENV_ROOT="${{TCL_VENV-}}"
fi
_TCLPKG_POSIX_VENV_ACTIVE=x

export TCL_VENV={}
export TCLLIBPATH={}"${{_OLD_TCL_VENV_TCLLIBPATH:+ $_OLD_TCL_VENV_TCLLIBPATH}}"
export PATH={}:"${{_OLD_TCL_VENV_PATH-}}"
PS1={}"${{_OLD_TCL_VENV_PS1-}}"
export PS1
"#,
        root.0, prefix.0, bin.0, prompt.0
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn posix_path_component_admission_does_not_restrict_executable_words() {
        let path = Path::new("/actual:executable");
        assert!(PosixLiteral::path(path).is_ok());
        assert!(PosixLiteral::path_component(path).is_err());
        assert!(activation(Path::new("/actual:venv"), "prompt").is_err());
    }
}

#[cfg(all(test, unix))]
mod presence_tests {
    use super::*;

    #[test]
    fn posix_activation_restores_actual_presence_and_reuses_one_original_baseline() {
        let base = std::env::temp_dir().join(format!(
            "tclpkg-presence-{}",
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        std::fs::create_dir_all(&base).unwrap();
        let root = base.join("venv 'literal'");
        let source = activation(&root, "prompt 'literal'").unwrap();
        let activation_path = base.join("activate");
        std::fs::write(&activation_path, source).unwrap();
        let report = "printf '%s\\000' \"${PATH+x}\" \"${PATH-}\" \"${TCLLIBPATH+x}\" \"${TCLLIBPATH-}\" \"${PS1+x}\" \"${PS1-}\" \"${TCL_VENV+x}\" \"${TCL_VENV-}\"\n";
        let mut driver = String::new();
        for seed in [
            "unset PATH; TCLLIBPATH=; PS1='original prompt'; TCL_VENV=\n",
            "PATH=; unset TCLLIBPATH; PS1=; TCL_VENV='original root'\n",
            "unset PATH TCLLIBPATH PS1 TCL_VENV\n",
            "PATH=; TCLLIBPATH=; PS1=; TCL_VENV=\n",
        ] {
            driver.push_str(seed);
            driver.push_str(report);
            driver.push_str(". \"$ACTIVATION\"\n");
            driver.push_str(report);
            driver.push_str(". \"$ACTIVATION\"\n");
            driver.push_str(report);
            driver.push_str("deactivate\n");
            driver.push_str(report);
        }
        let profile = tcl_sandbox::Profile::new("venv-posix-presence-control", "/bin/sh", &base)
            .arg("-")
            .set_env("ACTIVATION", activation_path.as_os_str())
            .stdin_bytes(driver.into_bytes());
        let outcome =
            crate::exec::execute(&profile, &tcl_sandbox::SandboxPolicy::default()).unwrap();
        assert!(outcome.success, "{:?}", outcome.stderr);
        assert!(outcome.stderr.is_empty(), "{:?}", outcome.stderr);
        let values = outcome
            .stdout
            .strip_suffix(&[0])
            .unwrap()
            .split(|byte| *byte == 0)
            .collect::<Vec<_>>();
        assert_eq!(values.len(), 4 * 4 * 8);
        for lifecycle in values.chunks_exact(32) {
            assert_eq!(&lifecycle[..8], &lifecycle[24..]);
            assert_eq!(&lifecycle[8..16], &lifecycle[16..24]);
            assert_eq!(lifecycle[14], b"x");
            assert_eq!(lifecycle[15], root.to_str().unwrap().as_bytes());
        }
        std::fs::remove_dir_all(base).unwrap();
    }
    #[test]
    fn posix_activation_refuses_missing_or_invalid_retained_presence_metadata() {
        let base = std::env::temp_dir().join(format!(
            "tclpkg-presence-invalid-{}",
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        std::fs::create_dir_all(&base).unwrap();
        let path = base.join("activate");
        std::fs::write(&path, activation(&base.join("venv"), "prompt").unwrap()).unwrap();
        for corruption in [
            "unset _OLD_TCL_VENV_PATH_SET",
            "_OLD_TCL_VENV_PATH_SET=invalid",
        ] {
            let driver = format!(
                r#"PATH=original
TCLLIBPATH=original
PS1=original
TCL_VENV=original
. "$ACTIVATION"
{corruption}
printf '%s\000' "$PATH" "$TCLLIBPATH" "$PS1" "$TCL_VENV"
if . "$ACTIVATION"; then exit 40; fi
if deactivate; then exit 41; fi
printf '%s\000' "$PATH" "$TCLLIBPATH" "$PS1" "$TCL_VENV"
"#
            );
            let profile =
                tcl_sandbox::Profile::new("venv-posix-invalid-state-control", "/bin/sh", &base)
                    .arg("-")
                    .set_env("ACTIVATION", path.as_os_str())
                    .stdin_bytes(driver.into_bytes());
            let outcome =
                crate::exec::execute(&profile, &tcl_sandbox::SandboxPolicy::default()).unwrap();
            assert!(outcome.success, "{:?}", outcome.stderr);
            let values = outcome
                .stdout
                .strip_suffix(&[0])
                .unwrap()
                .split(|byte| *byte == 0)
                .collect::<Vec<_>>();
            assert_eq!(values.len(), 8);
            assert_eq!(&values[..4], &values[4..]);
            assert_eq!(
                outcome
                    .stderr
                    .split(|byte| *byte == b'\n')
                    .filter(|line| !line.is_empty())
                    .count(),
                2
            );
        }
        std::fs::remove_dir_all(base).unwrap();
    }
}
