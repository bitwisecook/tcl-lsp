# Emulates `cargo xtask gen-bigip-grammars` (rust/xtask/src/gen_bigip_grammars.rs)
# while xtask cannot be built (disk). The real drift gate verifies it later.
import json, re, sys
root = sys.argv[1]
def rd(p): return open(f"{root}/{p}").read()
gen = rd("rust/xtask/src/gen_bigip_grammars.rs")
def rust_list(src, name):
    m = re.search(r"pub const %s: &\[&str\] = &\[(.*?)\];" % name, src, re.S)
    return re.findall(r'"([^"]+)"', m.group(1))
tok = rd("rust/tcl-bigip/src/apl/tokens.rs")
FIELD = rust_list(tok, "FIELD_TYPE_KEYWORDS"); ATTR = rust_list(tok, "ATTRIBUTE_KEYWORDS")
VALID = rust_list(tok, "VALIDATOR_NAMES"); SECT = rust_list(tok, "SECTION_KEYWORDS")
conf = rd("rust/tcl-bigip/src/conf_tokens.rs")
MODULES = rust_list(conf, "MODULES")
kr = re.search(r"pub const KEYED_REFERENCES.*?= &\[(.*?)\n\];", conf, re.S).group(1)
KEYED = re.findall(r'\("([^"]+)", BigipTokenKind::(\w+)\)', kr)
mon = rd("rust/tcl-bigip/src/value/monitor_expression.rs")
consts = dict(re.findall(r'pub const (\w+_WORD): &str = "([^"]+)";', mon))
GW = [consts[w] for w in re.search(r"GRAMMAR_WORDS: \[&str; 5\] = \[(.*?)\];", mon).group(1).replace(" ","").split(",")]
def any_of(ws):
    return "\n".join("    " + " ".join(f'"{w}"' for w in ws[i:i+6]) for i in range(0, len(ws), 6))
def template(fn):
    i = gen.index(f"fn {fn}(")
    body = gen[i:]
    s = body.index('r#"') + 3
    e = body.index('"#', s)
    return body[s:e]
def fmt(t, **kw):
    out = re.sub(r"\{(\w+)\}", lambda m: kw[m.group(1)] if m.group(1) in kw else m.group(0), t)
    return out.replace("{{", "{").replace("}}", "}")
# guard: no literal {name} placeholders that are real scm text
apl = fmt(template("render_zed_apl"), field_types=any_of(FIELD), validators="|".join(VALID),
          attributes=" ".join(f'"{w}"' for w in ATTR))
bigip = fmt(template("render_zed_bigip"), keys=any_of([k for k, _ in KEYED]))
PROV = "Generated by `cargo xtask gen-bigip-grammars`"
def prov(g, rule, owner):
    orig = g["repository"][rule].get("comment", "")
    base = orig.split("\n\n" + PROV)[0]
    note = f"{PROV} from {owner}; lexical display only."
    return note if not base else f"{base}\n\n{note}"
def set_comment(g, rule, c):
    r = g["repository"][rule]
    if "comment" in r: r["comment"] = c
    else: g["repository"][rule] = {"comment": c, **r}
ident = "[A-Za-z_][A-Za-z0-9_.]*"
g = json.loads(rd("editors/vscode/syntaxes/apl.tmLanguage.json"))
for rule, owner, rx in [
    ("section", "tcl_bigip::apl::tokens::SECTION_KEYWORDS", r"(?<=^|\s)(%s)(?=\s|$|\{)(?:\s+(%s))?" % ("|".join(SECT), ident)),
    ("validator", "tcl_bigip::apl::tokens::VALIDATOR_NAMES", r'(?<=^|\s)(validator)\s+(")(%s)(")' % "|".join(VALID)),
    ("field", "tcl_bigip::apl::tokens::FIELD_TYPE_KEYWORDS", r"(?<=^|\s)(%s)(?=\s)(?:\s+(%s))?" % ("|".join(FIELD), ident)),
    ("attribute", "tcl_bigip::apl::tokens::ATTRIBUTE_KEYWORDS", r"(?<=^|\s)(%s)(?=\s|$)" % "|".join(ATTR)),
]:
    g["repository"][rule]["match"] = rx
    set_comment(g, rule, prov(g, rule, owner))
vapl = json.dumps(g, indent=2, ensure_ascii=False) + "\n"
g = json.loads(rd("editors/vscode/syntaxes/bigip.tmLanguage.json"))
g["repository"]["declaration"]["match"] = r"^(%s)\s+([a-z0-9-]+)((?:\s+[a-z0-9-]+)*)" % "|".join(MODULES)
set_comment(g, "declaration", prov(g, "declaration", "tcl_bigip::conf_tokens::MODULES"))
SC = {"Pool": ("pool", "entity.name.type.pool.bigip"), "Profile": ("profile", "entity.name.type.profile.bigip"), "Vlan": ("vlan", "entity.name.type.vlan.bigip")}
pats = []
for kind in ["Pool", "Profile", "Vlan"]:
    keys = [k for k, kk in KEYED if kk == kind]
    pats.append({"match": r"(?<=^|\s)(%s)\s+([^\s{}]+)" % "|".join(keys),
                 "captures": {"1": {"name": "variable.other.property.bigip"}, "2": {"name": SC[kind][1]}}})
g["repository"]["typed-object-reference"]["patterns"] = pats
set_comment(g, "typed-object-reference", prov(g, "typed-object-reference", "tcl_bigip::conf_tokens::KEYED_REFERENCES"))
mk = [k for k, kk in KEYED if kk == "Monitor"]
g["repository"]["monitor-expression"]["begin"] = r"(?<=^|\s)(%s)(?=\s|$)" % "|".join(mk)
g["repository"]["monitor-expression"]["patterns"][0]["match"] = r"(?<=^|\s)(%s)(?=\s|$)" % "|".join(GW)
set_comment(g, "monitor-expression", prov(g, "monitor-expression", "tcl_bigip::conf_tokens::KEYED_REFERENCES and tcl_bigip::value::monitor_expression::GRAMMAR_WORDS"))
vbig = json.dumps(g, indent=2, ensure_ascii=False) + "\n"
for path, content in [("editors/zed/languages/apl/highlights.scm", apl), ("grammars/tree-sitter-apl/queries/highlights.scm", apl),
                      ("editors/zed/languages/bigip/highlights.scm", bigip), ("grammars/tree-sitter-bigip/queries/highlights.scm", bigip),
                      ("editors/vscode/syntaxes/apl.tmLanguage.json", vapl), ("editors/vscode/syntaxes/bigip.tmLanguage.json", vbig)]:
    open(f"{root}/{path}", "w").write(content)
    print("wrote", path)
