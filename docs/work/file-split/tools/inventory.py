#!/usr/bin/env python3
"""List Rust files over a line limit and what kind of file each is."""

import re
import sys
from pathlib import Path

LIMIT = 2000
ROOTS = ("rust", "runtime/rust")
GENERATED_MARKERS = ("@generated", "DO NOT EDIT", "Generated by", "generated by `", "This file is generated")
TEST_MODULE = re.compile(r"^mod (\w+) \{$")


def is_generated(path: Path, head: str) -> bool:
    name = path.name
    if name.startswith("generated_") or "/bigip/data/" in path.as_posix():
        return True
    return any(marker in head for marker in GENERATED_MARKERS)


def inline_test_lines(lines: list[str]) -> int:
    """Lines inside top-level `#[cfg(test)] mod name { ... }` blocks."""
    total = 0
    index = 0
    while index < len(lines):
        if lines[index] == "#[cfg(test)]":
            cursor = index + 1
            while cursor < len(lines) and (lines[cursor].startswith("#[") or lines[cursor].startswith("///")):
                cursor += 1
            if cursor < len(lines) and TEST_MODULE.match(lines[cursor]):
                end = cursor + 1
                while end < len(lines) and lines[end] != "}":
                    end += 1
                total += end - cursor - 1
                index = end
        index += 1
    return total


def kind_of(path: Path) -> str:
    posix = path.as_posix()
    name = path.name
    if "/tests/" in posix or "/benches/" in posix or name == "tests.rs" or name.endswith("_tests.rs") or name.endswith("_test.rs"):
        return "test"
    return "production"


def main() -> int:
    root = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.cwd()
    rows = []
    for tree in ROOTS:
        for path in sorted((root / tree).rglob("*.rs")):
            if "target" in path.parts:
                continue
            text = path.read_text(encoding="utf-8", errors="replace")
            lines = text.split("\n")
            if len(lines) <= LIMIT:
                continue
            relative = path.relative_to(root)
            generated = is_generated(relative, "\n".join(lines[:30]))
            rows.append((len(lines), relative.as_posix(), "generated" if generated else kind_of(relative), inline_test_lines(lines)))
    rows.sort(reverse=True)
    for count, path, kind, tests in rows:
        print(f"{count}\t{kind}\t{tests}\t{path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
