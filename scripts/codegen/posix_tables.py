CASE = re.compile(r'case\s+(E\w+):\s*return\s*"((?:[^"\\]|\\.)*)"', re.DOTALL)


def cases(text, start, end):
    body = text[text.index(start) : text.index(end)]
    return CASE.findall(body)


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    tmp = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "tmp"
    out = HEADER + [
        "",
        "// @generated by scripts/codegen/posix_tables.py from each release's",
        "// generic/tclPosixStr.c. Do not edit by hand.",
        "",
    ]
    latest_ids = []
    for table, tree, releases in GENERATIONS:
        text = (tmp / tree / "generic/tclPosixStr.c").read_text(encoding="latin-1")
        ids = [name for name, _ in cases(text, "\nTcl_ErrnoId(", "\nTcl_ErrnoMsg(")]
        msgs = cases(text, "\nTcl_ErrnoMsg(", "\nTcl_SignalId(")
        latest_ids = ids
        out.append(f"/// `Tcl_ErrnoId`'s names in {releases}.")
        out.append(f"pub(super) const IDS_{table}: &[&str] = &[")
        out += [f"    {rust_str(n)}," for n in ids]
        out.append("];")
        out.append("")
        out.append(f"/// `Tcl_ErrnoMsg`'s text in {releases}.")
        out.append(f"pub(super) const MESSAGES_{table}: &[(&str, &str)] = &[")
        out += [f"    ({rust_str(n)}, {rust_str(m)})," for n, m in msgs]
        out.append("];")
        out.append("")
    out.append(
        "/// Host errno → name, in `Tcl_ErrnoId`'s case order: where two names share"
    )
    out.append(
        "/// a number on a host, the first listed wins, as C's duplicate guards choose."
    )
    out.append('#[cfg(any(unix, target_os = "wasi"))]')
    out.append("pub(super) const NUMBERS: &[(i32, &str)] = &[")
    for name in dict.fromkeys(latest_ids):
        if name in PORTABLE:
            out.append(f'    (libc::{name}, "{name}"),')
        elif name not in NOT_IN_LINUX_LIBC:
            out.append('    #[cfg(target_os = "linux")]')
            out.append(f'    (libc::{name}, "{name}"),')
    out.append("];")
    out.append("")
    out.append('#[cfg(not(any(unix, target_os = "wasi")))]')
    out.append("pub(super) const NUMBERS: &[(i32, &str)] = &[];")
    OUT.write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
